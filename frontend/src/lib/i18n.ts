const DICT = { en, hi } as const;

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: Key, vars?: Record<string, string>) => string };
const I18nCtx = createContext<Ctx>({ lang: "en", setLang: () => {}, t: (k) => en[k] });

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const lang = useSyncExternalStore(subscribe, getLang, getLangServer);
  useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  const setLang = useCallback((l: Lang) => { localStorage.setItem(KEY, l); subs.forEach(cb => cb()); }, []);
  const t = useCallback((k: Key, vars?: Record<string, string>) => {
    let s: string = DICT[lang][k] ?? en[k];
    if (vars) for (const [a, b] of Object.entries(vars)) s = s.replace(`{${a}}`, b);
    return s;
  }, [lang]);
  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return createElement(I18nCtx.Provider, { value }, children);
}

export function useI18n() { return useContext(I18nCtx); }
