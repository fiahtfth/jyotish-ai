"""The report: a deterministic, computed reading for a chart.

build_report() gathers the chart's locked facts, its running dashas and —
when predictions are allowed — a 12-month outlook per domain produced by
precision.evaluate(). Everything in the response is computed; the prose
in `reading` is assembled from those numbers, never generated by an LLM,
and carries no numerical probabilities.
"""
from datetime import date, timedelta

from jhora.panchanga import drik

from . import constants as K
from . import panchang, precision, sensitivity, prediction
from .engine import BirthInput, engine

_MANGAL_HOUSES = {1, 2, 4, 7, 8, 12}   # Kuja dosha houses from lagna/Moon

_OUTLOOK_DAYS = 365


def _running_vimshottari(birth: BirthInput, today: date) -> list[dict]:
    try:
        return engine.running_vimshottari(birth, (today.year, today.month,
                                                  today.day))
    except Exception:
        return []


def _strength_summary(facts) -> dict:
    """Strongest/weakest graha by shadbala rupas (row 7, Sun..Saturn)."""
    shad = facts.get("shadbala")
    if not shad or len(shad) <= 7:
        return {}
    rows = {K.PLANET_NAMES[pid]: shad[7][pid]
            for pid in range(min(7, len(shad[7])))}
    best = max(rows, key=rows.get)
    worst = min(rows, key=rows.get)
    return {"strongest": {"planet": best, "rupas": round(rows[best], 2)},
            "weakest": {"planet": worst, "rupas": round(rows[worst], 2)},
            "all_rupas": {k: round(v, 2) for k, v in rows.items()}}


def _mangal_dosha(facts) -> dict:
    """Kuja (Mangal) dosha — Mars in 1/2/4/7/8/12 from the lagna; the
    wider school also counts it from the Moon."""
    mars = facts["planets"]["Mars"]
    from_moon = (mars["sign"] - facts["planets"]["Moon"]["sign"]) % 12 + 1
    return {"present": mars["house"] in _MANGAL_HOUSES,
            "house_from_lagna": mars["house"],
            "also_from_moon": from_moon in _MANGAL_HOUSES}


def _today_section(facts, birth: BirthInput, today: date) -> dict:
    try:
        return panchang.daily_panchang(
            today, panchang.place_of(birth), facts).get("personal") or {}
    except Exception:
        return {}


def _ordinal(n: int) -> str:
    return f"{n}{'st' if n == 1 else 'nd' if n == 2 else 'rd' if n == 3 else 'th'}"


def _chart_section(facts) -> dict:
    lagna = facts["lagna"]
    moon = facts["planets"]["Moon"]
    sun = facts["planets"]["Sun"]
    func = facts["functional"]
    kar = facts["jaimini"]["karakas"]
    return {
        "lagna": {"sign": lagna["sign_name"], "lord": lagna["lord"],
                  "nakshatra": lagna["nakshatra"]["name"]},
        "moon": {"sign": moon["sign_name"],
                 "nakshatra": moon["nakshatra"],
                 "house_from_lagna": moon["house"]},
        "sun": {"sign": sun["sign_name"]},
        "yogakaraka": func["yogakaraka"],
        "functional_benefics": func["benefics"],
        "functional_malefics": func["malefics"],
        "karakas": {"atmakaraka": kar.get("Atmakaraka"),
                    "amatyakaraka": kar.get("Amatyakaraka"),
                    "darakaraka": kar.get("Darakaraka")},
        "strength": _strength_summary(facts),
        "mangal_dosha": _mangal_dosha(facts),
    }


def _outlook(facts, birth: BirthInput, calibrated: bool,
             today: date) -> list[dict]:
    end = today + timedelta(days=_OUTLOOK_DAYS)
    out = []
    from . import classical
    for domain in ("career", "education", "relationship", "relocation", "finance", "direction", "health"):
        spec = K.DOMAINS[domain]
        natal = classical.promise(facts, domain)
        prec = precision.evaluate(facts, birth, domain, today, end,
                                  calibrated=calibrated)
        sens = sensitivity.evaluate(facts, birth, domain, today, end, calibrated, base=prec)
        analysis = dict(prec["verdict"])
        analysis["precision"] = {"confirmation": prec["confirmation"]["label"],
                                 "yogini": prec["confirmation"]["yogini"]["verdict"],
                                 "sudarshana": prec["confirmation"]["sudarshana"]["verdict"],
                                 "layer_verdicts": prec["layer_verdicts"]}
        analysis["sensitivity"] = sens
        classical.apply(analysis, facts, birth, domain, today, end, calibrated, prec, natal)
        analysis["decision"] = prediction.decide("general outlook", analysis)
        windows = [{"start": w["start"], "end": w["end"],
                    "fast_trigger": w.get("fast_trigger")}
                   for w in analysis["precision"]["timing_windows"]]
        out.append({
            "analysis": analysis, "sensitivity": sens,
            "domain": domain,
            "label": spec["label"],
            "convergence": prec["verdict"]["convergence"],
            "confirmation": prec["confirmation"]["label"],
            "timing_windows": windows if sens["timing_stable"] else [],
            "magnitude": prec["magnitude"]["label"],
            "watch_months": prec["fast_triggers"]["watch_months"],
            "layer_verdicts": prec["layer_verdicts"],
            **({"disclaimer": spec["disclaimer"]}
               if spec.get("disclaimer") else {}),
        })
    return out


def _domain_line(d: dict) -> str:
    grade = d["analysis"]["classical"]["promise"].lower()
    parts = [f"{d['domain'].capitalize()} — the natal and divisional assessment is {grade}"]
    if d["timing_windows"]:
        parts.append("strongest weeks " + "; ".join(
            f"{w['start']} → {w['end']}" for w in d["timing_windows"]))
    if d["magnitude"]:
        parts.append(f"indicated magnitude {d['magnitude']}")
    return ". ".join(parts) + "."


def build_report(facts, birth: BirthInput, *, calibrated: bool,
                 predictions_allowed: bool, subject: str | None = None,
                 today: date | None = None) -> dict:
    """Structured report for the active profile. `subject` is the chart
    owner's name when the chart belongs to a family member, else None."""
    today = today or date.today()
    run = _running_vimshottari(birth, today)
    chart = _chart_section(facts)
    today_personal = _today_section(facts, birth, today)
    who = subject or "you"

    sections = {"generated_for": subject or "self", "date": today.isoformat(),
                "calibrated": calibrated, "chart": chart,
                "current_periods": {"vimshottari": run[:3]},
                "today": today_personal,
                "predictions_allowed": predictions_allowed}

    lines = [f"{f'{who}’s' if subject else 'Your'} chart — computed from "
             f"{facts['meta']['birth_datetime_local']} at "
             f"{facts['meta']['place']}.",
             f"{chart['lagna']['sign']} lagna ({chart['lagna']['nakshatra']}), "
             f"lord {chart['lagna']['lord']}. "
             f"Moon in {chart['moon']['sign']} ({chart['moon']['nakshatra']['name']}, "
             f"house {chart['moon']['house_from_lagna']}); "
             f"Sun in {chart['sun']['sign']}."]
    if chart["yogakaraka"]:
        lines.append(f"Yogakaraka: {chart['yogakaraka']}. Functional benefics: "
                     f"{', '.join(chart['functional_benefics'])}; "
                     f"malefics: {', '.join(chart['functional_malefics'])}.")
    if chart.get("strength"):
        s = chart["strength"]
        lines.append(f"Shadbala — strongest: {s['strongest']['planet']} "
                     f"({s['strongest']['rupas']} rupas); weakest: "
                     f"{s['weakest']['planet']} ({s['weakest']['rupas']}).")
    md = chart["mangal_dosha"]
    if md["present"]:
        lines.append(
            f"Kuja (Mangal) dosha: Mars sits in the "
            f"{_ordinal(md['house_from_lagna'])} from the lagna"
            + (" — a dosha house from the Moon too."
               if md["also_from_moon"] else "."))
    if today_personal:
        t = today_personal.get("tara") or {}
        sfm = today_personal.get("saturn_from_moon") or {}
        mh = today_personal.get("moon_house_from_janma")
        line = f"Today: {t.get('name')} tara"
        if mh:
            line += f", Moon in the {_ordinal(mh)} from the natal Moon"
        if sfm.get("sade_sati"):
            line += (f"; Saturn transits the {_ordinal(sfm['house'])} "
                     "from the natal Moon — sade sati period")
        elif sfm.get("ashtama"):
            line += "; ashtama shani (Saturn in the 8th from the Moon)"
        elif sfm.get("kantaka"):
            line += "; kantaka shani (Saturn in the 4th from the Moon)"
        lines.append(line + ".")
    if run:
        lines.append("Current Vimshottari: " + " / ".join(
            r["lords"][0] for r in run[:2])
                     + f" — {run[0]['lords'][0]} period runs to {run[0]['end']}.")

    if predictions_allowed:
        domains = _outlook(facts, birth, calibrated, today)
        watch = sorted({m for d in domains for m in d["watch_months"]})
        sections["domains"] = domains
        sections["watch_months"] = watch
        lines.append("Twelve-month outlook (four-pillar verdict plus filters — "
                     "the weeks where traditional indicators concentrate):")
        lines += ["- " + _domain_line(d) for d in domains]
        if watch:
            lines.append("Watch months (eclipse near a natal planet): "
                         + ", ".join(watch) + ".")
        if not calibrated:
            lines.append("Birth time is not yet calibrated, so the "
                         "lagna-sensitive layers (Lagna Sudarshana, Shadbala "
                         "magnitude, annual-chart triggers) were left out.")
    else:
        sections["domains"] = []
        sections["watch_months"] = []
        lines.append("Predictions are paused for this chart — the three "
                     "past-event checks haven't lined up yet. The chart "
                     "facts above are still fully computed.")

    sections["reading"] = lines
    return sections
